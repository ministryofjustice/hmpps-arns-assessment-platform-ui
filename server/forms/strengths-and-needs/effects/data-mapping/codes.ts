/** Equivalent of Kotlin's `Field.lower` (`name.lowercase()`). */
export function fieldLower(field: Field): string {
  return field.toLowerCase()
}

const FIELD_NAMES = new Set<string>(Object.values(Field))

/** Equivalent of Kotlin's `Field.valueOf(name)` - throws if `name` is not a Field member. */
export function fieldFromName(name: string): Field {
  if (!FIELD_NAMES.has(name)) {
    throw new Error(`No enum constant Field.${name}`)
  }
  return name as Field
}

